"""Проверки, отделяющие данные от путей файловой системы.

Единственное место, где живут эти два правила. Копий не заводить: они защищают
от одной и той же ошибки в разных файлах, а расходятся копии молча.

История. Проверка `is_safe_name` появилась в `preprod.py` после ревью
2026-08-02: имя персонажа приходит из frontmatter сценария, то есть его пишет
модель по брифу человека, и напрямую превращается в путь. Ревью безопасности
2026-09-05 нашло тот же класс ошибки ещё в двух местах, добавленных позже:
идентификатор аудио-единицы в `audio.json` и ссылки `refs` в `shots.json`. Оба
файла — данные, которые пишет модель, и оба напрямую становились путями.
"""
from __future__ import annotations

from pathlib import Path


def is_safe_name(name: str) -> bool:
    """Годится ли строка как ЕДИНСТВЕННЫЙ компонент пути.

    Отсекает пустое, точки, разделители обоих видов и абсолютные пути. Без этой
    проверки имя вида ``../../secret`` читает и ПИШЕТ за пределами проекта
    (воспроизведено ревью 2026-08-02 и повторно 2026-09-05).
    """
    if not name or name in (".", ".."):
        return False
    if any(sep in name for sep in ("/", "\\")):
        return False
    return not Path(name).is_absolute()


def inside(root: Path, candidate: Path) -> bool:
    """Лежит ли путь внутри корня ПОСЛЕ разрешения ссылок и ``..``.

    Существование файла ничего не говорит о праве его читать: ``root/../secret``
    существует и находится снаружи. Сравнение делается по разрешённым путям,
    потому что именно разрешённый путь откроет операционная система.

    Отдельно про абсолютные пути: ``Path("a/b") / "C:/tmp/x"`` отбрасывает левую
    часть целиком и даёт ``C:\\tmp\\x``. Такой «относительный» путь молча
    выводит наружу, поэтому склейка проверяется здесь, а не рядом с ней.
    """
    try:
        Path(candidate).resolve().relative_to(Path(root).resolve())
    except (ValueError, OSError):
        return False
    return True
